-- Reduce false trigger emails by removing noisy generic keywords and keeping
-- only high-signal escalation phrases for the escalation queue.

DELETE FROM keyword_categories
WHERE category = 'escalation_trigger'
  AND keyword IN (
    'TODAY',
    'EOD',
    'ASAP',
    'ACTION REQUIRED',
    'RESPONSE REQUIRED',
    'REPLY REQUIRED',
    'RESPONSE PENDING',
    'AWAITING RESPONSE',
    'AWAITING CONFIRMATION',
    'PENDING CONFIRMATION',
    'DEADLINE',
    'FINAL DEADLINE'
  );

-- High-signal escalation trigger keywords only.
INSERT IGNORE INTO keyword_categories (category, keyword) VALUES
('escalation_trigger', 'URGENT'),
('escalation_trigger', 'CRITICAL'),
('escalation_trigger', 'IMMEDIATE ACTION'),
('escalation_trigger', 'CLIENT ESCALATION'),
